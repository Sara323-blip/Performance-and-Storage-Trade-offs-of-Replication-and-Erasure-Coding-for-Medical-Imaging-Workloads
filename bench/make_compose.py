"""Generate the compose files in compose/ so that topology and parity are explicit and consistent.

Usage: python -m bench.make_compose
All files take the image and the data directory from the environment (set by bench.run_all):
  MINIO_IMAGE   pinned image, never "latest"
  DATA_DIR      absolute host directory for the drives of this run
  PARITY        parity for the erasure-coded files (EC:PARITY)
"""
import os

HEADER = """# GENERATED by bench/make_compose.py - do not edit by hand.
# {desc}
x-minio: &minio
  image: ${{MINIO_IMAGE:?set MINIO_IMAGE}}
  command: server --console-address ":9001" {topology}
  environment:
    MINIO_ROOT_USER: ${{MINIO_ROOT_USER:-minioadmin}}
    MINIO_ROOT_PASSWORD: ${{MINIO_ROOT_PASSWORD:-minioadmin123}}
{extra_env}  networks:
    - minio-net

services:
"""

NODE = """  minio{i}:
    <<: *minio
    hostname: minio{i}
    volumes:
{volumes}
    ports:
      - "{port}:9000"
"""

FOOTER = """
networks:
  minio-net:
    driver: bridge
"""


def ec(nodes, drives_per_node, desc, path):
    topology = f"http://minio{{1...{nodes}}}/data{{1...{drives_per_node}}}" if drives_per_node > 1 \
        else f"http://minio{{1...{nodes}}}/data"
    extra = '    MINIO_STORAGE_CLASS_STANDARD: "EC:${PARITY:?set PARITY}"\n'
    out = HEADER.format(desc=desc, topology=topology, extra_env=extra)
    for i in range(1, nodes + 1):
        vols = "\n".join(
            f"      - ${{DATA_DIR:?set DATA_DIR}}/node{i}/drive{d}:/data{d if drives_per_node > 1 else ''}"
            for d in range(1, drives_per_node + 1))
        out += NODE.format(i=i, volumes=vols, port=9100 + i)
    write(path, out + FOOTER)


def repl(copies, desc, path):
    # independent single-drive servers: no cluster, no erasure coding; replication is done by the client
    out = ("# GENERATED by bench/make_compose.py - do not edit by hand.\n# " + desc + "\n"
           "x-minio: &minio\n"
           "  image: ${MINIO_IMAGE:?set MINIO_IMAGE}\n"
           "  command: server /data --console-address \":9001\"\n"
           "  environment:\n"
           "    MINIO_ROOT_USER: ${MINIO_ROOT_USER:-minioadmin}\n"
           "    MINIO_ROOT_PASSWORD: ${MINIO_ROOT_PASSWORD:-minioadmin123}\n"
           "  networks:\n    - minio-net\n\nservices:\n")
    for i in range(1, copies + 1):
        out += (f"  minio{i}:\n    <<: *minio\n    hostname: minio{i}\n    volumes:\n"
                f"      - ${{DATA_DIR:?set DATA_DIR}}/node{i}/drive1:/data\n    ports:\n"
                f"      - \"{9100 + i}:9000\"\n")
    write(path, out + FOOTER)


def write(path, text):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w") as f:
        f.write(text)


if __name__ == "__main__":
    root = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "compose")
    ec(3, 2, "6 drives (3 nodes x 2) = one 6-drive erasure set; EC:2 gives 4 data + 2 parity.",
       os.path.join(root, "ec6.yml"))
    ec(7, 1, "7 drives (7 nodes x 1) = one 7-drive erasure set; EC:2 gives 5 data + 2 parity.",
       os.path.join(root, "ec7.yml"))
    ec(5, 2, "10 drives (5 nodes x 2) = one 10-drive erasure set; EC:PARITY gives (10-PARITY) data + PARITY parity "
             "(PARITY must be 2..5).", os.path.join(root, "ec10.yml"))
    repl(3, "Three independent single-drive servers. MinIO has no N-way replication storage class, so the "
            "benchmark client writes every object to all three.", os.path.join(root, "repl3.yml"))
    print("compose files written")
